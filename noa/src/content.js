// What a gift prompt needs, in one Hebrew line ("תבדוק מה רשום על פרחים · המידה שלה: טבעת"), or ''.
export function giftNeedsHint(prompt) {
  const n = prompt && prompt.needs;
  if (!n) return '';
  const parts = [];
  if (n.fact) { const c = FACT_CATEGORIES.find(x => x.id === n.fact); if (c) parts.push('מה רשום אצלך על ' + c.label); }
  if (n.size) { const s = SIZE_FIELDS.find(x => x.id === n.size); if (s) parts.push('המידה שלה: ' + s.label); }
  if (n.place === 'want') parts.push('מקום מ"רוצים לנסות"');
  if (n.place === 'us') parts.push('המקומות של שניכם');
  if (n.place === 'her') parts.push('מקום שהיא אוהבת');
  if (n.loveLanguage) { const l = LOVE_LANGUAGES.find(x => x.id === n.loveLanguage); if (l) parts.push('שפת אהבה: ' + l.label); }
  return parts.join(' · ');
}

// Gift prompts personalised by what he wrote about her: [{prompt, facts, size, places, score}] best first.
// facts: her facts (love/like) in the prompt's fact category; size: the size value; places: matching places.
// Prompts whose needs are unmet still appear (lower), so an empty app still gets ideas.
export function giftSuggestions(data, opts = {}) {
  const d = data || {};
  const facts = (d.facts || []).filter(f => f && (f.sentiment === 'love' || f.sentiment === 'like'));
  const sizes = (d.profile && d.profile.sizes) || {};
  const places = (d.places || []).filter(Boolean);
  const loves = (d.profile && d.profile.loveLanguages) || [];
  const out = GIFT_PROMPTS.filter(p => (opts.category ? p.category === opts.category : true) && (opts.maxBudget != null ? p.budget <= opts.maxBudget : true)).map(prompt => {
    const n = prompt.needs || {};
    const fs = n.fact ? facts.filter(f => f.category === n.fact).sort((a, b) => (b.starred ? 1 : 0) - (a.starred ? 1 : 0) || (a.sentiment === 'love' ? -1 : 0) - (b.sentiment === 'love' ? -1 : 0)) : [];
    const size = n.size ? String(sizes[n.size] || '').trim() : '';
    const ps = n.place ? places.filter(p => p.lovedBy === n.place) : [];
    let score = 0;
    if (fs.length) score += 3 + Math.min(fs.length, 3);
    if (size) score += 3;
    if (ps.length) score += 2;
    if (n.loveLanguage && loves.length) { const i = loves.indexOf(n.loveLanguage); if (i >= 0) score += Math.max(1, 3 - i); }
    if ((n.fact && !fs.length) || (n.size && !size) || (n.place && !ps.length)) score -= 1;
    return { prompt, facts: fs.slice(0, 3), size, places: ps.slice(0, 3), score, hint: giftNeedsHint(prompt) };
  });
  out.sort((a, b) => b.score - a.score || GIFT_PROMPTS.indexOf(a.prompt) - GIFT_PROMPTS.indexOf(b.prompt));
  return opts.limit ? out.slice(0, opts.limit) : out;
}

