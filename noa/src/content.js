// A small deterministic PRNG (mulberry32) and a string hash (FNV-1a) for seeded picks.
function _ctHash(s) { let h = 0x811c9dc5; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193); } return h >>> 0; }
export function seededRandom(seed) {
  let a = typeof seed === 'number' ? seed >>> 0 : _ctHash(String(seed));
  return function () { a = (a + 0x6D2B79F5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}

function _ctDayNum(dateKey) {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(dateKey || ''));
  if (!m) return 0;
  return Math.round(Date.UTC(+m[1], +m[2] - 1, +m[3]) / 86400000);
}

// The same item all day long, a different one tomorrow; each run through the list is a seeded shuffle, so nothing
// repeats until every item has been shown. opts.exclude: ids (array or Set) to skip (e.g. gestures already done);
// opts.skip: n → the n-th next pick of the day ("רעיון אחר"). Returns null for an empty list.
export function pickDaily(list, dateKey, salt = '', opts = {}) {
  const items = Array.isArray(list) ? list : [];
  if (!items.length) return null;
  const ex = opts.exclude instanceof Set ? opts.exclude : new Set(opts.exclude || []);
  const pool = items.filter(x => !(x && ex.has(x.id)));
  const usable = pool.length ? pool : items;
  const n = usable.length, day = _ctDayNum(dateKey) + (opts.skip || 0);
  const cycle = Math.floor(day / n), pos = ((day % n) + n) % n;
  const order = usable.map((_, i) => i), rnd = seededRandom(String(salt) + ':' + cycle + ':' + n);
  for (let i = n - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); const t = order[i]; order[i] = order[j]; order[j] = t; }
  return usable[order[pos]];
}

// Does an item match a filter object? Each key: undefined/null/'' → ignored; array → item value is one of them;
// function → predicate on the value; otherwise equality. An item value of 'any' matches every filter value
// (season 'any' suits summer and winter); an array item value (tags) matches when it includes the filter value.
// Special keys: maxBudget, maxMinutes, exclude (ids).
function _ctMatches(item, filter) {
  for (const [k, want] of Object.entries(filter || {})) {
    if (want === undefined || want === null || want === '') continue;
    if (k === 'maxBudget') { if (!(item.budget <= want)) return false; continue; }
    if (k === 'maxMinutes') { if (!(item.minutes <= want)) return false; continue; }
    if (k === 'exclude') { const ex = want instanceof Set ? want : new Set(want); if (ex.has(item.id)) return false; continue; }
    const have = item[k];
    if (typeof want === 'function') { if (!want(have, item)) return false; continue; }
    if (have === 'any') continue;
    if (Array.isArray(want)) { if (Array.isArray(have) ? !have.some(h => want.includes(h)) : !want.includes(have)) return false; continue; }
    if (Array.isArray(have)) { if (!have.includes(want)) return false; continue; }
    if (have !== want) return false;
  }
  return true;
}

// The items that pass `filter` (a predicate function or a filter object, see above).
export function contentFilter(list, filter) {
  const items = Array.isArray(list) ? list.filter(Boolean) : [];
  if (!filter) return items;
  return typeof filter === 'function' ? items.filter(filter) : items.filter(x => _ctMatches(x, filter));
}

// One random item that passes `filter`, or null. rng: () => [0,1) (default Math.random; pass seededRandom(...)
// for reproducible picks).
export function randomPick(list, filter, rng = Math.random) {
  const pool = contentFilter(list, filter);
  if (!pool.length) return null;
  return pool[Math.min(pool.length - 1, Math.floor(rng() * pool.length))];
}

// Israeli seasons for the idea filter: April–October → 'summer', November–March → 'winter'.
export function seasonOf(dateKey) {
  const m = /^\d{4}-(\d{2})/.exec(String(dateKey || ''));
  const month = m ? +m[1] : new Date().getMonth() + 1;
  return month >= 4 && month <= 10 ? 'summer' : 'winter';
}

// Today's small gesture for the home card: skips gestures done in the last `days` (default 45) days.
// skip: how many times he tapped "רעיון אחר".
export function gestureOfDay(data, dateKey, skip = 0, days = 45) {
  const done = (data && data.gestures && data.gestures.done) || {};
  const recent = new Set();
  const today = _ctDayNum(dateKey);
  for (const [id, when] of Object.entries(done)) if (today - _ctDayNum(when) < days) recent.add(id);
  return pickDaily(GESTURES, dateKey, 'gesture', { exclude: recent, skip });
}

// A question he has not asked yet (optionally of one level; level 'thirtysix' draws from THIRTY_SIX in order).
export function nextQuestion(data, level, rng = Math.random) {
  const asked = (data && data.asked) || {};
  if (level === 'thirtysix') return THIRTY_SIX.find(q => !asked[q.id]) || null;
  const pool = contentFilter(QUESTIONS, { level: level || undefined });
  return randomPick(pool, q => !asked[q.id], rng) || randomPick(pool, null, rng);
}

